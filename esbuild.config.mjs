import esbuild from 'esbuild';
import fs from 'node:fs';
import { builtinModules } from 'node:module';
import process from 'node:process';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const copyAssetsPlugin = {
	name: 'copy-external-data',
	setup(build) {
		build.onEnd(() => {
			fs.copyFileSync('src/presets/default-presets.json', 'lt-default-presets.json');
			fs.copyFileSync('src/data/stem-formula-db.json', 'lt-stem-formula-db.json');
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: {
		main: 'src/main.ts',
		'lt-engines.chunk': 'src/chunks/engines.ts',
		'lt-builder.chunk': 'src/chunks/builder.ts',
		'lt-calculator.chunk': 'src/chunks/calculator.ts',
	},
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outdir: '.',
	minify: prod,
	plugins: [copyAssetsPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
